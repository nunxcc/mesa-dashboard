import type { MenuItem } from '@/types/domain';

/**
 * Generation hints that the UI has no business knowing about. They live here
 * rather than on `MenuItem` so the domain type stays a description of a menu
 * item, not a description of how we fake one.
 */
export interface MenuSeed extends MenuItem {
  /** Relative pick weight within its category. */
  popularity: number;
  /**
   * Whether the item is offered on delivery marketplaces. A bica does not
   * survive twenty minutes on a scooter, and the real menus reflect that —
   * which is a large part of why delivery baskets look so different.
   */
  travelsWell: boolean;
}

